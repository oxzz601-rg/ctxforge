"""Collect, rank and pack repository files into a fixed token budget.

The pipeline is deliberately boring and offline:

1. walk the repository, skipping vendored, binary and oversized files;
2. score every file with BM25 over the query plus structural signals
   (path hits, README/manifest importance, imports of better-ranked files);
3. greedily pack the highest scoring files, truncating large ones so one
   big file cannot eat the whole budget;
4. render a deterministic markdown bundle with a repository map.
"""

from __future__ import annotations

import fnmatch
import math
import os
import pathlib
import re
from dataclasses import dataclass, field, replace

IGNORED_DIRS = {
    ".git", ".hg", ".svn", ".venv", "venv", "env", "node_modules", "__pycache__",
    "dist", "build", "out", "target", "vendor", ".next", ".nuxt", ".cache",
    ".pytest_cache", ".mypy_cache", ".ruff_cache", "coverage", ".idea", ".vscode",
}

BINARY_SUFFIXES = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf", ".zip", ".gz", ".tar",
    ".bz2", ".xz", ".7z", ".mp3", ".mp4", ".mov", ".avi", ".wav", ".woff", ".woff2",
    ".ttf", ".otf", ".eot", ".so", ".dll", ".dylib", ".exe", ".pyc", ".pyo", ".class",
    ".jar", ".sqlite", ".db", ".bin", ".pt", ".pth", ".onnx", ".safetensors",
}

LANGUAGES = {
    ".py": "python", ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "tsx", ".jsx": "jsx", ".go": "go", ".rs": "rust",
    ".java": "java", ".kt": "kotlin", ".rb": "ruby", ".php": "php", ".c": "c",
    ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".hpp": "cpp", ".cs": "csharp",
    ".sh": "bash", ".bash": "bash", ".zsh": "bash", ".sql": "sql", ".yml": "yaml",
    ".yaml": "yaml", ".toml": "toml", ".json": "json", ".md": "markdown",
    ".html": "html", ".css": "css", ".scss": "scss", ".swift": "swift", ".lua": "lua",
}

MANIFESTS = {
    "package.json", "pyproject.toml", "setup.py", "cargo.toml", "go.mod", "pom.xml",
    "build.gradle", "gemfile", "requirements.txt", "composer.json", "makefile", "dockerfile",
}

ENTRYPOINTS = {"main.py", "app.py", "cli.py", "server.py", "index.js", "index.ts", "main.go", "main.rs", "__main__.py"}

_TOKEN = re.compile(r"\w+|[^\w\s]")
_IMPORT = re.compile(r"^\s*(?:from\s+([\w.]+)\s+import|import\s+([\w.]+))", re.MULTILINE)
_JS_IMPORT = re.compile(r"(?:require\(|from\s+)['\"]([^'\"]+)['\"]")

MAX_FILE_BYTES = 400_000


def estimate_tokens(text):
    """Cheap, conservative token estimate (roughly words plus punctuation)."""
    return max(1, len(_TOKEN.findall(text)))


def tokenize(text):
    return re.findall(r"[a-z0-9_]+|[/.][a-z0-9_]+|[A-Z]?[a-z]+", text.casefold())


@dataclass
class SourceFile:
    path: str
    text: str
    tokens: int
    score: float = 0.0
    reason: str = ""
    truncated: bool = False

    def language(self):
        return LANGUAGES.get(pathlib.Path(self.path).suffix.lower(), "")


@dataclass
class Bundle:
    query: str
    budget: int
    files: tuple = ()
    skipped: tuple = ()
    total_tokens: int = 0

    def manifest(self):
        return {
            "query": self.query,
            "budget": self.budget,
            "total_tokens": self.total_tokens,
            "files": [
                {
                    "path": item.path,
                    "tokens": item.tokens,
                    "score": round(item.score, 3),
                    "reason": item.reason,
                    "truncated": item.truncated,
                }
                for item in self.files
            ],
            "skipped": list(self.skipped),
        }

    def repository_map(self):
        return "\n".join("- `{}` ({} tokens)".format(item.path, item.tokens) for item in self.files)

    def render(self):
        parts = [
            "# Context bundle: {}".format(self.query or "repository overview"),
            "",
            "{} file(s), {} tokens of a {} token budget. Generated by ctxforge.".format(
                len(self.files), self.total_tokens, self.budget
            ),
            "",
            "## Repository map",
            "",
            self.repository_map(),
            "",
        ]
        for item in self.files:
            parts.append("## {} ({} tokens{})".format(item.path, item.tokens, ", truncated" if item.truncated else ""))
            parts.append("")
            parts.append("```{}".format(item.language()))
            parts.append(item.text.rstrip("\n"))
            parts.append("```")
            parts.append("")
        return "\n".join(parts).rstrip() + "\n"


def is_ignored(rel_path, include=(), exclude=()):
    if any(fnmatch.fnmatch(rel_path, pattern) for pattern in exclude):
        return True
    if include and not any(fnmatch.fnmatch(rel_path, pattern) for pattern in include):
        return True
    return False


def collect(root, include=(), exclude=(), max_bytes=MAX_FILE_BYTES):
    root = pathlib.Path(root)
    if not root.is_dir():
        raise NotADirectoryError("{} is not a directory".format(root))
    files, skipped = [], []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in IGNORED_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            path = pathlib.Path(dirpath) / name
            rel = path.relative_to(root).as_posix()
            if is_ignored(rel, include, exclude):
                skipped.append(rel)
                continue
            if path.suffix.lower() in BINARY_SUFFIXES or name.endswith(".min.js"):
                skipped.append(rel)
                continue
            try:
                if path.stat().st_size > max_bytes:
                    skipped.append(rel)
                    continue
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                skipped.append(rel)
                continue
            if "\x00" in text:
                skipped.append(rel)
                continue
            files.append(SourceFile(path=rel, text=text, tokens=estimate_tokens(text)))
    return files, skipped


def _structural_bonus(path, query_terms):
    name = pathlib.Path(path).name.lower()
    lower = path.lower()
    bonus = 0.0
    if name in MANIFESTS:
        bonus += 0.6
    if name in ENTRYPOINTS or "/" not in path and name.startswith("main."):
        bonus += 0.8
    if name.startswith("readme"):
        bonus += 0.7
    if path.count("/") <= 1:
        bonus += 0.15
    for term in query_terms:
        if term in lower:
            bonus += 1.5
    if "test" in lower or "spec" in lower:
        bonus -= 0.25
    return bonus


def _imports(files):
    graph = {}
    by_stem = {}
    for item in files:
        stem = pathlib.Path(item.path).stem
        by_stem.setdefault(stem, []).append(item.path)
    for item in files:
        names = [a or b for a, b in _IMPORT.findall(item.text)]
        names += _JS_IMPORT.findall(item.text)
        targets = set()
        for name in names:
            tail = re.split(r"[./]", name.replace("\\", "."))[-1]
            for candidate in by_stem.get(tail, []):
                if candidate != item.path:
                    targets.add(candidate)
            if name.endswith(".js") or name.endswith(".ts") or "\"" in name:
                for candidate in by_stem.get(pathlib.Path(name).stem, []):
                    if candidate != item.path:
                        targets.add(candidate)
        graph[item.path] = sorted(targets)[:12]
    return graph


def rank(files, query="", boost_imports=True):
    """BM25 over the query, blended with structural and import-graph signals."""
    if not files:
        return []
    terms = tokenize(query)
    docs = [tokenize(item.path + "\n" + item.text) for item in files]
    doc_freq = {}
    for doc in docs:
        for term in set(doc):
            doc_freq[term] = doc_freq.get(term, 0) + 1
    total_docs = len(files)
    average_length = sum(len(doc) for doc in docs) / total_docs or 1.0
    scores = {}
    for item, doc in zip(files, docs):
        counts = {}
        for term in doc:
            counts[term] = counts.get(term, 0) + 1
        score = 0.0
        for term in terms:
            frequency = counts.get(term, 0)
            if not frequency:
                continue
            idf = math.log(1 + (total_docs - doc_freq.get(term, 0) + 0.5) / (doc_freq.get(term, 0) + 0.5))
            score += idf * frequency * 2.2 / (frequency + 1.2 * (0.25 + 0.75 * len(doc) / average_length))
        score += _structural_bonus(item.path, terms)
        scores[item.path] = score
    graph = _imports(files) if boost_imports else {}
    if boost_imports and scores:
        best = max(scores.values()) or 1.0
        changed = True
        rounds = 0
        while changed and rounds < 2:
            changed = False
            rounds += 1
            for path, targets in graph.items():
                parent = scores.get(path, 0.0)
                for target in targets:
                    bonus = 0.12 * parent
                    if parent > 0 and scores.get(target, 0.0) < best * 0.5 and bonus > 0.01:
                        scores[target] = scores.get(target, 0.0) + bonus
                        changed = True
    ranked = []
    for item in files:
        score = scores.get(item.path, 0.0)
        reason = "query match" if any(term in item.path.casefold() for term in terms) else "structure"
        if item.path.casefold() in {term for term in terms}:
            reason = "path match"
        ranked.append(replace(item, score=score, reason=reason))
    ranked.sort(key=lambda item: (-item.score, item.path))
    return ranked


def _truncate(item, limit_tokens):
    if item.tokens <= limit_tokens:
        return item
    lines = item.text.splitlines()
    head, tail = [], []
    used = 0
    for line in lines:
        cost = estimate_tokens(line) + 1
        if used + cost > limit_tokens * 0.6:
            break
        head.append(line)
        used += cost
    for line in reversed(lines[len(head):]):
        cost = estimate_tokens(line) + 1
        if used + cost > limit_tokens:
            break
        tail.append(line)
        used += cost
    omitted = max(0, len(lines) - len(head) - len(tail))
    text = "\n".join(head + ["", "# ... {} line(s) omitted by ctxforge ...".format(omitted), ""] + list(reversed(tail)))
    return replace(item, text=text, tokens=estimate_tokens(text) + 8, truncated=True)


def build_bundle(root, query="", budget=60000, include=(), exclude=(), max_file_tokens=8000, boost_imports=True):
    files, skipped = collect(root, include=include, exclude=exclude)
    ranked = rank(files, query=query, boost_imports=boost_imports)
    chosen, total = [], 0
    for item in ranked:
        if item.score <= 0 and chosen:
            continue
        remaining = budget - total
        if remaining <= 64:
            break
        limit = min(max_file_tokens, remaining - 24)
        if limit <= 32:
            break
        candidate = _truncate(item, limit)
        chosen.append(candidate)
        total += candidate.tokens
    chosen.sort(key=lambda item: item.path)
    return Bundle(query=query, budget=budget, files=tuple(chosen), skipped=tuple(skipped), total_tokens=total)
